-- Rebuild learning tracking from scratch. Retain transcript-transfer metadata,
-- which shares this table but is used by graduation and transcript workflows.
BEGIN;

CREATE TEMP TABLE _lesson_progress_transfer_backup (
    student_id VARCHAR(100) NOT NULL,
    lesson_id BIGINT NOT NULL,
    is_transferred BOOLEAN NOT NULL DEFAULT FALSE,
    grade VARCHAR(20),
    transfer_request_id BIGINT,
    transferred_by VARCHAR(100),
    transferred_at TIMESTAMPTZ,
    PRIMARY KEY (student_id, lesson_id)
) ON COMMIT DROP;

DO $$
BEGIN
    IF to_regclass('public.lesson_progress') IS NOT NULL THEN
        INSERT INTO pg_temp._lesson_progress_transfer_backup
            (student_id, lesson_id, is_transferred, grade, transfer_request_id, transferred_by, transferred_at)
        SELECT student_id, lesson_id, COALESCE(is_transferred, FALSE), grade,
               transfer_request_id, transferred_by, transferred_at
        FROM public.lesson_progress
        WHERE COALESCE(is_transferred, FALSE) OR UPPER(COALESCE(grade, '')) = 'TR'
        ON CONFLICT (student_id, lesson_id) DO NOTHING;
    END IF;
END $$;

DROP TABLE IF EXISTS public.lesson_progress;
DROP TABLE IF EXISTS public.video_watch_sessions;
DROP TABLE IF EXISTS public.learning_events;

CREATE TABLE public.lesson_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(100) NOT NULL,
    user_id VARCHAR(100) GENERATED ALWAYS AS (student_id) STORED,
    lesson_id BIGINT NOT NULL,
    progress_value NUMERIC(10,2) NOT NULL DEFAULT 0,
    progress_type VARCHAR(20) NOT NULL DEFAULT 'document',
    is_completed BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Media-specific values let one lesson retain a video position and a
    -- document percentage at the same time for existing course summaries.
    document_progress_percent NUMERIC(5,2) NOT NULL DEFAULT 0,
    document_page_index INTEGER NOT NULL DEFAULT 0,
    video_progress_percent NUMERIC(5,2) NOT NULL DEFAULT 0,
    video_position_seconds INTEGER NOT NULL DEFAULT 0,
    opened_count INTEGER NOT NULL DEFAULT 0,
    video_open_count INTEGER NOT NULL DEFAULT 0,
    first_opened_at TIMESTAMPTZ,
    last_opened_at TIMESTAMPTZ,
    last_activity_at TIMESTAMPTZ,

    -- Transcript transfer fields are not progress tracking and remain intact.
    is_transferred BOOLEAN NOT NULL DEFAULT FALSE,
    grade VARCHAR(20),
    transfer_request_id BIGINT,
    transferred_by VARCHAR(100),
    transferred_at TIMESTAMPTZ,
    UNIQUE (student_id, lesson_id)
);

INSERT INTO public.lesson_progress
    (student_id, lesson_id, is_transferred, grade, transfer_request_id, transferred_by, transferred_at)
SELECT student_id, lesson_id, is_transferred, grade, transfer_request_id, transferred_by, transferred_at
FROM pg_temp._lesson_progress_transfer_backup
ON CONFLICT (student_id, lesson_id) DO NOTHING;

CREATE INDEX idx_lesson_progress_student_lesson
    ON public.lesson_progress (student_id, lesson_id);

CREATE OR REPLACE FUNCTION public.touch_lesson_progress_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;
CREATE TRIGGER lesson_progress_touch_updated_at
    BEFORE UPDATE ON public.lesson_progress
    FOR EACH ROW EXECUTE FUNCTION public.touch_lesson_progress_updated_at();

COMMIT;
