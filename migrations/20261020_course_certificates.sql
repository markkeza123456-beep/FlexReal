BEGIN;

CREATE TABLE IF NOT EXISTS public.course_certificates (
    certificate_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR NOT NULL REFERENCES public.students(user_id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES public.courses(course_id) ON DELETE CASCADE,
    certificate_number VARCHAR(80) NOT NULL UNIQUE,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    document_bucket TEXT NOT NULL,
    document_object_path TEXT NOT NULL,
    UNIQUE (student_id, course_id)
);

CREATE INDEX IF NOT EXISTS course_certificates_student_issued_idx
    ON public.course_certificates (student_id, issued_at DESC);

COMMIT;
